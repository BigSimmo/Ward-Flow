/**
 * Client-side privacy guard to prevent real Australian healthcare identifiers
 * from being transmitted or saved to development/cloud storage.
 *
 * Scans payloads for:
 * 1. Australian Medicare numbers (10 digits starting with 2-6, optionally with the card position digit)
 * 2. Australian hospital identifiers (UMRN / UR / MRN with 6-10 digits)
 * 3. Australian mobile and landline telephone numbers
 */

export type SyntheticCheckResult = { safe: true } | { safe: false; reason: string; sample?: string };

// 10 digits, starts with 2, 3, 4, 5, or 6 (optionally formatted: 2xxx xxxxx x), plus the optional
// card position digit (A4-1), matching the redaction pattern in privacy.ts.
const MEDICARE_PATTERN = /\b([2-6]\d{3}[ -]?\d{5}[ -]?\d(?:[ -]?\d)?)\b/;

// Explicit hospital patient record markers followed by 6-10 digits
const HOSPITAL_RECORD_PATTERN = /\b(?:UMRN|MRN|UR[N#]?)\s*[:#-]?\s*(\d{6,10})\b/i;

// Australian phone numbers: Mobile 04xx xxx xxx or +61 4xx, and landlines in every area code
// ((02), (03), (07), (08), or +61 2/3/7/8), matching the redaction pattern in privacy.ts (A4-1).
const PHONE_PATTERN =
  /(?:\+?61\s*4\d{2}[ -]?\d{3}[ -]?\d{3}|\b04\d{2}[ -]?\d{3}[ -]?\d{3}|\+?61\s*\(?[2378]\)?\s*\d{4}[ -]?\d{4}|\(?\b0[2378]\)?\s*\d{4}[ -]?\d{4})\b/;

// Audit E-06: the ACMA keeps 5550 xxxx and 7010 xxxx in each landline area code for fiction, so no
// real service or person can hold one. The demo's own numbers (the Settings profile, the reference
// teams) are 08 5550 0xxx and must not be refused as real.
const FICTITIOUS_LANDLINE = /^(?:61|0)?[2378](?:5550|7010)\d{4}$/;
const fictitiousPhone = (match: string) => FICTITIOUS_LANDLINE.test(match.replace(/\D/g, ""));

// Only strip the exact synthetic token shape generated by the demo data fixtures. In particular,
// do not consume arbitrary text after DEMO/SYNTHETIC: it may contain a real identifier.
const SYNTHETIC_TOKEN_PATTERN = /\bSYNTHETIC-\d{8}\b/gi;

function scanString(value: string): SyntheticCheckResult | null {
  // Fictitious phone numbers are blanked first so a compact international one (`+61855500142`)
  // cannot read as an 11-digit Medicare number; real numbers beside them are still scanned.
  const sanitized = value
    .replace(SYNTHETIC_TOKEN_PATTERN, "")
    .replace(new RegExp(PHONE_PATTERN, "g"), (match) => (fictitiousPhone(match) ? " " : match));

  const medicareMatch = MEDICARE_PATTERN.exec(sanitized);
  if (medicareMatch) {
    // Redact digits for privacy in the error message
    const redacted = `${medicareMatch[1].slice(0, 3)}****${medicareMatch[1].slice(-2)}`;
    return {
      safe: false,
      reason: "Potential Australian Medicare number detected",
      sample: redacted,
    };
  }

  const recordMatch = HOSPITAL_RECORD_PATTERN.exec(sanitized);
  if (recordMatch) {
    return {
      safe: false,
      reason: "Potential real hospital record number (UMRN/MRN/UR) detected",
      sample: recordMatch[0].slice(0, 4) + "****",
    };
  }

  const phoneMatch = sanitized.match(new RegExp(PHONE_PATTERN, "g"))?.find((match) => !fictitiousPhone(match));
  if (phoneMatch) {
    return {
      safe: false,
      reason: "Potential real telephone number detected",
      sample: phoneMatch.slice(0, 4) + "****",
    };
  }

  return null;
}

export function checkSyntheticPayload(payload: unknown, maxDepth = 16): SyntheticCheckResult {
  if (payload === null || payload === undefined) {
    return { safe: true };
  }

  const seen = new WeakSet<object>();

  function walk(node: unknown, depth: number): SyntheticCheckResult {
    if (depth > maxDepth) {
      return {
        safe: false,
        reason: "Payload nesting too deep to scan for real identifiers",
      };
    }

    if (typeof node === "string") {
      const violation = scanString(node);
      if (violation) return violation;
      return { safe: true };
    }

    if (typeof node === "number") {
      const violation = scanString(String(node));
      if (violation) return violation;
      return { safe: true };
    }

    if (typeof node === "object" && node !== null) {
      if (seen.has(node)) {
        return { safe: true };
      }
      seen.add(node);

      if (Array.isArray(node)) {
        for (const item of node) {
          const result = walk(item, depth + 1);
          if (!result.safe) return result;
        }
      } else {
        for (const [key, value] of Object.entries(node)) {
          // Check key itself
          const keyViolation = scanString(key);
          if (keyViolation) return keyViolation;

          // Check combined key-value if key is a record indicator and value is numeric or string
          if (typeof value === "number" || typeof value === "string") {
            const combinedViolation = scanString(`${key}: ${value}`);
            if (combinedViolation) return combinedViolation;

            if (/UMRN|MRN|\bUR\b/i.test(key)) {
              const asRecordViolation = scanString(`UMRN: ${value}`);
              if (asRecordViolation) return asRecordViolation;
            }
          }

          // Check value
          const valueViolation = walk(value, depth + 1);
          if (!valueViolation.safe) return valueViolation;
        }
      }
    }

    return { safe: true };
  }

  return walk(payload, 0);
}
